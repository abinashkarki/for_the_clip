"""Optional local editorial judgment, isolated so inference memory is released."""
import importlib.util
import json
import os
import subprocess
import sys
import threading
from uuid import uuid4

from . import telemetry
from .paths import data_root, model_directory as runtime_model_directory

MODEL_ID = 'mlx-community/Qwen3-4B-Instruct-2507-4bit'
MODEL_REVISION = '50d427756c6b1b2fe0c0a10f67fbda1fc8e82c1b'
_INFERENCE_LOCK = threading.RLock()


def model_directory():
    return runtime_model_directory('qwen3-4b-editor-4bit', override='CLIPPIE_EDITOR_MODEL')


def status():
    path = model_directory()
    return {'model': MODEL_ID, 'revision': MODEL_REVISION,
            'installed': importlib.util.find_spec('mlx_lm') is not None,
            'weights_ready': (path/'model.safetensors').is_file(), 'device': 'Apple MLX', 'quantization': '4bit'}


def generate(messages, max_tokens=1200, wait=True):
    if not isinstance(max_tokens, int) or isinstance(max_tokens, bool) or not 1 <= max_tokens <= 1200:
        raise ValueError('Local output budget must be from 1 to 1200 tokens.')
    if not _INFERENCE_LOCK.acquire(blocking=wait):
        raise RuntimeError('Local editor is busy.')
    try:
        return _generate(messages, max_tokens)
    finally:
        _INFERENCE_LOCK.release()


@telemetry.instrument('model', fatal=False)
def _generate(messages, max_tokens):
    telemetry.attributes(model_id=MODEL_ID, model_revision=MODEL_REVISION, max_tokens=max_tokens)
    state = status()
    if not state['installed'] or not state['weights_ready']:
        raise RuntimeError('Local editor is not prepared. Install the editor extra and run scripts/prepare_editor.py, or explicitly select Baseline.')
    try:
        result = subprocess.run([sys.executable, '-m', 'clippie.local_editor_worker'],
            input=json.dumps({'model_path': str(model_directory().resolve()), 'messages': messages, 'max_tokens': max_tokens, 'traceparent': telemetry.propagation()}),
            text=True, capture_output=True, timeout=240,
            env={**os.environ, 'HF_HUB_OFFLINE': '1', 'TOKENIZERS_PARALLELISM': 'false'})
    except subprocess.TimeoutExpired as exc:
        raise RuntimeError('Local editorial planning exceeded four minutes. No baseline fallback was used.') from exc
    if result.returncode:
        raise RuntimeError('Local editor failed: '+result.stderr.strip()[-1200:])
    try:
        envelope = json.loads(result.stdout)
    except (ValueError, TypeError) as exc:
        raise RuntimeError('Local editor returned an invalid response envelope; no fallback was used.') from exc
    telemetry.attributes(**envelope.get('usage', {}),
        peak_memory_gb=envelope.get('metrics', {}).get('peak_memory_gb'),
        generation_tps=envelope.get('metrics', {}).get('generation_tps'),
        model_seconds=envelope.get('metrics', {}).get('seconds'),
        finish_reason=envelope.get('finish_reason'), runtime_version=envelope.get('settings', {}).get('runtime'))
    child_span = envelope.pop('telemetry_span', None)
    if child_span and telemetry.propagation() and isinstance(child_span, dict):
        # Generated by our isolated worker, sanitized again at the export boundary.
        try:
            telemetry.recorder().enqueue('span', child_span)
        except Exception:
            pass
    traces = data_root() / 'editor-runs'
    traces.mkdir(parents=True, exist_ok=True)
    trace = traces/(uuid4().hex+'.json')
    trace.write_text(json.dumps({'model': MODEL_ID, 'revision': MODEL_REVISION,
                                'messages': messages, 'response': envelope}, ensure_ascii=False, indent=2))
    envelope['trace_path'] = str(trace.resolve())
    telemetry.attributes(diagnostic_id=trace.stem)
    return envelope
