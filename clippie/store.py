"""Small durable job store. One JSON document per job keeps the prototype inspectable."""
import json
import sqlite3
import threading
from datetime import datetime, timezone
from pathlib import Path


def now():
    return datetime.now(timezone.utc).isoformat()


class Store:
    def __init__(self, root: Path):
        self.root = root.resolve()
        from .storage_safety import assert_compatible
        assert_compatible(self.root)
        self.root.mkdir(parents=True, exist_ok=True)
        self.path = self.root / 'clippie.sqlite3'
        self.lock = threading.RLock()
        with self.connect() as db:
            db.execute('CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, document TEXT NOT NULL)')

    def connect(self):
        db = sqlite3.connect(self.path, timeout=30)
        db.execute('PRAGMA journal_mode=WAL')
        return db

    def get(self, job_id):
        with self.connect() as db:
            row = db.execute('SELECT document FROM jobs WHERE id=?', (job_id,)).fetchone()
        if row is None:
            raise KeyError(job_id)
        return json.loads(row[0])

    def save(self, job):
        with self.lock, self.connect() as db:
            db.execute('INSERT INTO jobs VALUES (?,?) ON CONFLICT(id) DO UPDATE SET document=excluded.document',
                       (job['id'], json.dumps(job, ensure_ascii=False, allow_nan=False)))
        return job

    def update(self, job_id, **values):
        with self.lock:
            job = self.get(job_id)
            job.update(values)
            return self.save(job)

    def all(self):
        with self.connect() as db:
            rows = db.execute('SELECT document FROM jobs ORDER BY rowid DESC').fetchall()
        return [json.loads(row[0]) for row in rows]

    def directory(self, job_id):
        # ID is generated by us and must already exist in the store.
        self.get(job_id)
        directory = self.root / job_id
        directory.mkdir(exist_ok=True)
        return directory

    def delete(self, job_id):
        """Remove a job record. Files are the caller's business (see lifecycle)."""
        with self.lock, self.connect() as db:
            db.execute('DELETE FROM jobs WHERE id=?', (job_id,))
